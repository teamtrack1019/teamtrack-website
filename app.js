async function handleContactSubmit(e) {
  e.preventDefault();
  const form = document.getElementById('contact-form');
  const success = document.getElementById('form-success');
  const submitBtn = form ? form.querySelector('button[type="submit"]') : null;
  
  const name = document.getElementById('input-name') ? document.getElementById('input-name').value : '';
  const company = document.getElementById('input-company') ? document.getElementById('input-company').value : '';
  const email = document.getElementById('input-email') ? document.getElementById('input-email').value : '';
  const phone = document.getElementById('input-phone') ? document.getElementById('input-phone').value : '';
  const interest = document.getElementById('input-interest') ? document.getElementById('input-interest').value : '';
  const message = document.getElementById('input-msg') ? document.getElementById('input-msg').value : '';

  if (submitBtn) {
    submitBtn.disabled = true;
    submitBtn.innerHTML = `
      <span class="flex items-center justify-center gap-2">
        <svg class="animate-spin h-4 w-4 text-slate-900" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
          <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
          <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
        </svg>
        <span>${currentLang === 'tr' ? 'Gönderiliyor...' : (currentLang === 'en' ? 'Sending...' : 'Wird gesendet...')}</span>
      </span>
    `;
  }

  const payload = { name, company, email, phone, interest, message };

  try {
    // 1. Send via native Vercel Serverless Function with Resend
    const res = await fetch('/api/contact', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify(payload)
    });

    if (!res.ok) {
      console.warn("API response status:", res.status);
    }

    // 2. Fallback to PHP backend if available
    try {
      const formData = new FormData(form);
      fetch('send_mail.php', { method: 'POST', body: formData }).catch(() => {});
    } catch (_) {}

  } catch (err) {
    console.warn("Contact form dispatch notice:", err);
  } finally {
    if (form && success) {
      form.classList.add('hidden');
      success.classList.remove('hidden');
      if (window.lucide) lucide.createIcons();
    }
  }
}

function updateCalculator() {
  const workersInput = document.getElementById('calc-workers');
  const rateInput = document.getElementById('calc-rate');
  const workersVal = document.getElementById('calc-workers-val');
  const rateVal = document.getElementById('calc-rate-val');
  const totalSavings = document.getElementById('calc-total-savings');
  const totalHours = document.getElementById('calc-total-hours');

  if (!workersInput || !rateInput) return;

  const workers = parseInt(workersInput.value, 10);
  const rate = parseInt(rateInput.value, 10);

  if (workersVal) workersVal.textContent = workers;
  if (rateVal) rateVal.textContent = rate + ' €';

  const hoursPerWorkerPerYear = 4.5 * 12; // 54 hours
  const totalSavedHours = workers * hoursPerWorkerPerYear;
  const annualSavings = totalSavedHours * rate;

  if (totalSavings) {
    totalSavings.textContent = annualSavings.toLocaleString(currentLang === 'de' ? 'de-DE' : (currentLang === 'tr' ? 'tr-TR' : 'en-US')) + ' €';
  }
  if (totalHours) {
    totalHours.textContent = totalSavedHours.toLocaleString() + (currentLang === 'tr' ? ' Saat / Yıl' : (currentLang === 'en' ? ' Hrs / Year' : ' Std / Jahr'));
  }
}


function toggleNavMenu() {
  const dropdown = document.getElementById('nav-menu-dropdown');
  const chevron = document.getElementById('nav-menu-chevron');
  if (dropdown) {
    const isHidden = dropdown.classList.contains('hidden');
    if (isHidden) {
      dropdown.classList.remove('hidden');
      if (chevron) chevron.classList.add('rotate-180');
    } else {
      dropdown.classList.add('hidden');
      if (chevron) chevron.classList.remove('rotate-180');
    }
  }
}

function closeNavMenu() {
  const dropdown = document.getElementById('nav-menu-dropdown');
  const chevron = document.getElementById('nav-menu-chevron');
  if (dropdown) dropdown.classList.add('hidden');
  if (chevron) chevron.classList.remove('rotate-180');
}

