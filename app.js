function changeLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;

  try {
    localStorage.setItem('teamtrack_lang', lang);
  } catch (e) {}

  // Update lang buttons
  ['de', 'en', 'tr'].forEach(l => {
    const btn = document.getElementById('lang-btn-' + l);
    if (btn) {
      if (l === lang) {
        btn.className = "px-2 sm:px-2.5 py-1 sm:py-1.5 rounded-lg bg-white shadow-sm text-cyan-700 font-extrabold transition";
      } else {
        btn.className = "px-2 sm:px-2.5 py-1 sm:py-1.5 rounded-lg text-slate-600 hover:text-slate-900 transition";
      }
    }
  });

  // Replace i18n text
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update showcase
  switchShowcaseTab(currentTab);

  // Update legal modal if open
  const modal = document.getElementById('legal-modal');
  if (modal && !modal.classList.contains('hidden')) {
    switchLegalTab(currentLegalTab);
  }
}

